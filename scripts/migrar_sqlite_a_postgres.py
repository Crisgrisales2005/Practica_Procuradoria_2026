#!/usr/bin/env python3
"""Migra data/sqlite/app.db → Supabase (PostgreSQL), preservando IDs.

modulos: caso especial — si init_db ya sembró los 13, no aborta; remapea por codigo.
documentos/chunks/items/intentos/srs_estado: aborta si ya hay filas (salvo --force).
"""

from __future__ import annotations

import argparse
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from backend.config import settings
from backend.db.connection import DatabaseError, get_connection, init_db

TABLAS_ESTRICTAS = ("documentos", "chunks", "items", "intentos", "srs_estado")

CODIGOS_ESPERADOS = frozenset(
    {
        "esp_01",
        "esp_02",
        "esp_03",
        "esp_04",
        "esp_05",
        "esp_06",
        "esp_07",
        "esp_08",
        "com_09",
        "com_10",
        "com_11",
        "com_12",
        "com_13",
    }
)


def _abrir_sqlite(path: Path) -> sqlite3.Connection:
    if not path.is_file():
        raise FileNotFoundError(f"No está el SQLite legado: {path}")
    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row
    return conn


def _contar(pg, tabla: str) -> int:
    row = pg.execute(f"SELECT COUNT(*) AS n FROM {tabla}").fetchone()
    return int(row["n"]) if row else 0


def _setval(pg, tabla: str) -> None:
    row = pg.execute(f"SELECT COALESCE(MAX(id), 0) AS m FROM {tabla}").fetchone()
    max_id = int(row["m"])
    # GENERATED BY DEFAULT AS IDENTITY → secuencia asociada
    pg.execute(
        "SELECT setval(pg_get_serial_sequence(%s, 'id'), %s, %s)",
        (tabla, max(max_id, 1), max_id > 0),
    )


def _mapa_modulos(pg) -> dict[tuple[str, str], int]:
    rows = pg.execute(
        "SELECT id, entidad, codigo FROM modulos WHERE entidad = %s",
        ("pgn",),
    ).fetchall()
    return {(r["entidad"], r["codigo"]): int(r["id"]) for r in rows}


def _asegurar_modulos(pg, sqlite_conn: sqlite3.Connection) -> dict[int, int]:
    """Devuelve mapa sqlite_modulo_id → postgres_modulo_id."""
    existentes = _mapa_modulos(pg)
    codigos_pg = {codigo for (_, codigo) in existentes}
    extras = codigos_pg - CODIGOS_ESPERADOS
    if extras:
        raise RuntimeError(
            f"modulos en Postgres tiene códigos inesperados: {sorted(extras)}. "
            "Abortando."
        )

    faltan = CODIGOS_ESPERADOS - codigos_pg
    if faltan:
        seed = (ROOT / "backend" / "db" / "seed_modulos.sql").read_text(encoding="utf-8")
        for bloque in seed.split(";"):
            stmt = bloque.strip()
            if stmt:
                pg.execute(stmt)
        existentes = _mapa_modulos(pg)
        codigos_pg = {codigo for (_, codigo) in existentes}
        if CODIGOS_ESPERADOS - codigos_pg:
            raise RuntimeError(
                f"Tras el seed aún faltan módulos: {sorted(CODIGOS_ESPERADOS - codigos_pg)}"
            )

    sqlite_rows = sqlite_conn.execute(
        "SELECT id, entidad, codigo FROM modulos WHERE entidad = 'pgn'"
    ).fetchall()
    remap: dict[int, int] = {}
    for row in sqlite_rows:
        key = (row["entidad"], row["codigo"])
        if key not in existentes:
            raise RuntimeError(
                f"Módulo SQLite {key} no está en el seed de Postgres."
            )
        remap[int(row["id"])] = existentes[key]
    return remap


def _vaciar_tablas_estrictas(pg) -> None:
    # Orden inverso a FKs
    for tabla in ("srs_estado", "intentos", "items", "chunks", "documentos"):
        pg.execute(f"TRUNCATE TABLE {tabla} RESTART IDENTITY CASCADE")


def migrar(*, sqlite_path: Path, force: bool) -> None:
    init_db()
    sqlite_conn = _abrir_sqlite(sqlite_path)
    pg = get_connection()
    try:
        if not force:
            ocupadas = [t for t in TABLAS_ESTRICTAS if _contar(pg, t) > 0]
            if ocupadas:
                raise RuntimeError(
                    "Supabase ya tiene datos en: "
                    + ", ".join(ocupadas)
                    + ". Si quieres reescribir esas tablas (no el seed de módulos), "
                    "repite con --force."
                )
        else:
            _vaciar_tablas_estrictas(pg)

        remap_mod = _asegurar_modulos(pg, sqlite_conn)
        print(f"modulos: {len(remap_mod)} códigos alineados por codigo (seed OK)")

        # documentos (ids preservados)
        docs = sqlite_conn.execute(
            "SELECT id, entidad, nombre_archivo, sha256, fecha_carga FROM documentos"
        ).fetchall()
        for d in docs:
            pg.execute(
                """
                INSERT INTO documentos (id, entidad, nombre_archivo, sha256, fecha_carga)
                VALUES (%s, %s, %s, %s, %s)
                """,
                (
                    int(d["id"]),
                    d["entidad"],
                    d["nombre_archivo"],
                    d["sha256"],
                    d["fecha_carga"],
                ),
            )
        print(f"documentos: {len(docs)}")

        chunks = sqlite_conn.execute(
            """
            SELECT id, documento_id, modulo_id, entidad, norma, articulo, texto, chroma_id
            FROM chunks
            """
        ).fetchall()
        for c in chunks:
            mid = remap_mod[int(c["modulo_id"])]
            pg.execute(
                """
                INSERT INTO chunks (
                    id, documento_id, modulo_id, entidad, norma, articulo, texto, chroma_id
                ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                """,
                (
                    int(c["id"]),
                    int(c["documento_id"]),
                    mid,
                    c["entidad"],
                    c["norma"],
                    c["articulo"],
                    c["texto"],
                    c["chroma_id"],
                ),
            )
        print(f"chunks: {len(chunks)}")

        items = sqlite_conn.execute(
            """
            SELECT id, entidad, modulo_id, parent_item_id, chunk_ids,
                   norma, articulo, enunciado, caso,
                   opciones_json, matriz_json, dudoso, creado_en
            FROM items
            """
        ).fetchall()
        for it in items:
            mid = remap_mod[int(it["modulo_id"])]
            parent = it["parent_item_id"]
            pg.execute(
                """
                INSERT INTO items (
                    id, entidad, modulo_id, parent_item_id, chunk_ids,
                    norma, articulo, enunciado, caso,
                    opciones_json, matriz_json, dudoso, creado_en
                ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                """,
                (
                    int(it["id"]),
                    it["entidad"],
                    mid,
                    int(parent) if parent is not None else None,
                    it["chunk_ids"],
                    it["norma"],
                    it["articulo"],
                    it["enunciado"],
                    it["caso"],
                    it["opciones_json"],
                    it["matriz_json"],
                    int(it["dudoso"] or 0),
                    it["creado_en"],
                ),
            )
        print(f"items: {len(items)}")

        intentos = sqlite_conn.execute(
            "SELECT id, item_id, puntaje, respondido_en FROM intentos"
        ).fetchall()
        for row in intentos:
            pg.execute(
                """
                INSERT INTO intentos (id, item_id, puntaje, respondido_en)
                VALUES (%s, %s, %s, %s)
                """,
                (
                    int(row["id"]),
                    int(row["item_id"]),
                    int(row["puntaje"]),
                    row["respondido_en"],
                ),
            )
        print(f"intentos: {len(intentos)}")

        srs = sqlite_conn.execute(
            """
            SELECT id, entidad, modulo_id, norma, articulo, chunk_id, nivel,
                   ease, intervalo_dias, reps, lapses, next_due
            FROM srs_estado
            """
        ).fetchall()
        for row in srs:
            mid = remap_mod[int(row["modulo_id"])]
            pg.execute(
                """
                INSERT INTO srs_estado (
                    id, entidad, modulo_id, norma, articulo, chunk_id, nivel,
                    ease, intervalo_dias, reps, lapses, next_due
                ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                """,
                (
                    int(row["id"]),
                    row["entidad"],
                    mid,
                    row["norma"],
                    row["articulo"],
                    int(row["chunk_id"]),
                    row["nivel"],
                    float(row["ease"]),
                    int(row["intervalo_dias"]),
                    int(row["reps"]),
                    int(row["lapses"]),
                    row["next_due"],
                ),
            )
        print(f"srs_estado: {len(srs)}")

        for tabla in (
            "modulos",
            "documentos",
            "chunks",
            "items",
            "intentos",
            "srs_estado",
        ):
            _setval(pg, tabla)

        pg.commit()
        print("Migración OK. Secuencias ajustadas.")
    except Exception:
        pg.rollback()
        raise
    finally:
        pg.close()
        sqlite_conn.close()


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Migra app.db (SQLite) a Supabase preservando IDs de chunks/items."
    )
    parser.add_argument(
        "--sqlite",
        type=Path,
        default=None,
        help="Ruta al app.db (default: data/sqlite/app.db del proyecto).",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Vacía documentos/chunks/items/intentos/srs_estado y reescribe. No borra el seed de módulos.",
    )
    args = parser.parse_args()

    sqlite_path = args.sqlite or settings.sqlite_path
    if not settings.has_database_url:
        print("Falta DATABASE_URL en .env.", file=sys.stderr)
        return 2

    try:
        migrar(sqlite_path=sqlite_path, force=args.force)
    except FileNotFoundError as exc:
        print(exc, file=sys.stderr)
        return 1
    except DatabaseError as exc:
        print(exc, file=sys.stderr)
        return 1
    except RuntimeError as exc:
        print(exc, file=sys.stderr)
        return 1
    except Exception as exc:
        print(f"Migración falló: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
