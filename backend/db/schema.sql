CREATE TABLE IF NOT EXISTS modulos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entidad TEXT NOT NULL DEFAULT 'pgn',
    codigo TEXT NOT NULL,
    nombre TEXT NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('especifico', 'comun')),
    orden INTEGER NOT NULL,
    UNIQUE (entidad, codigo)
);

CREATE TABLE IF NOT EXISTS documentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entidad TEXT NOT NULL DEFAULT 'pgn',
    nombre_archivo TEXT NOT NULL,
    sha256 TEXT NOT NULL,
    fecha_carga TEXT NOT NULL,
    UNIQUE (entidad, sha256)
);

CREATE TABLE IF NOT EXISTS chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id BIGINT NOT NULL REFERENCES documentos(id),
    modulo_id BIGINT NOT NULL REFERENCES modulos(id),
    entidad TEXT NOT NULL DEFAULT 'pgn',
    norma TEXT NOT NULL,
    articulo TEXT NOT NULL,
    texto TEXT NOT NULL,
    chroma_id TEXT
);

-- Asociación N:M chunk ↔ módulo (Ley 594 → esp_06 + com_13). Un solo chunk_id físico.
CREATE TABLE IF NOT EXISTS chunk_modulos (
    chunk_id BIGINT NOT NULL REFERENCES chunks(id) ON DELETE CASCADE,
    modulo_id BIGINT NOT NULL REFERENCES modulos(id),
    PRIMARY KEY (chunk_id, modulo_id)
);

CREATE INDEX IF NOT EXISTS idx_chunk_modulos_modulo ON chunk_modulos (modulo_id);

CREATE TABLE IF NOT EXISTS items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entidad TEXT NOT NULL DEFAULT 'pgn',
    modulo_id BIGINT NOT NULL REFERENCES modulos(id),
    parent_item_id BIGINT REFERENCES items(id),
    chunk_ids TEXT NOT NULL DEFAULT '[]',
    norma TEXT NOT NULL,
    articulo TEXT NOT NULL,
    enunciado TEXT NOT NULL,
    caso TEXT NOT NULL,
    opciones_json TEXT NOT NULL,
    matriz_json TEXT NOT NULL,
    dudoso SMALLINT NOT NULL DEFAULT 0,
    creado_en TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS intentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES items(id),
    puntaje INTEGER NOT NULL CHECK (puntaje IN (0, 2, 5)),
    respondido_en TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS srs_estado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entidad TEXT NOT NULL DEFAULT 'pgn',
    modulo_id BIGINT NOT NULL REFERENCES modulos(id),
    norma TEXT NOT NULL,
    articulo TEXT NOT NULL,
    chunk_id BIGINT NOT NULL REFERENCES chunks(id),
    nivel TEXT NOT NULL,
    ease DOUBLE PRECISION NOT NULL DEFAULT 2.5,
    intervalo_dias INTEGER NOT NULL DEFAULT 0,
    reps INTEGER NOT NULL DEFAULT 0,
    lapses INTEGER NOT NULL DEFAULT 0,
    next_due TEXT,
    -- UNIQUE sin modulo_id: mismo chunk_id = misma unidad de repaso (Fase 8).
    -- En DBs ya creadas, migrar_fase8_esquema() reemplaza el constraint antiguo.
    UNIQUE (entidad, norma, articulo, chunk_id, nivel)
);

CREATE INDEX IF NOT EXISTS idx_srs_next_due ON srs_estado (next_due);
CREATE INDEX IF NOT EXISTS idx_items_modulo_dudoso ON items (modulo_id, dudoso);
CREATE INDEX IF NOT EXISTS idx_intentos_item ON intentos (item_id);
